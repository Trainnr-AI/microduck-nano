"""Generate the firmware's robot_config_data.h from config/robot.json.

    python3 tools/gen_config.py            # write the header
    python3 tools/gen_config.py --check    # fail if the header is out of date

Also prints the servo angle limits in steps that follow from the joint table
(what would go into each servo's EEPROM, registers 9 and 11).

--check also checks that the name tables outside the firmware (the Python
client's, and the Rust runtime's) have one name per value of the firmware's
enums, so a new fault or result code cannot be decoded as the wrong name.
"""
import argparse
import ast
import json
import math
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROBOT_JSON = HERE.parent / "config" / "robot.json"
CORE = HERE.parent / "app" / "microduck" / "sketch" / "src" / "duck"
HEADER = CORE / "robot_config_data.h"
CLIENT = HERE.parent / "app" / "microduck" / "python" / "duck_client.py"
RUNTIME = HERE.parent.parent / "runtime" / "src"

JOINT_ORDER = ["left_hip_yaw", "left_hip_roll", "left_hip_pitch", "left_knee", "left_ankle",
               "neck_pitch", "head_pitch", "head_yaw", "head_roll",
               "right_hip_yaw", "right_hip_roll", "right_hip_pitch", "right_knee", "right_ankle", "beak"]
NUM_POSE_JOINTS = 14  # every joint but the beak (kNumPoseJoints)
POSE_JOINTS = JOINT_ORDER[:NUM_POSE_JOINTS]

# C++ enum (header in CORE) -> its name table in duck_client.py, and in the runtime as (file, constant).
NAME_TABLES = {
    "JointIndex": ("robot_config.h", "JOINTS", ("robot.rs", "JOINT_NAMES")),
    "Mode": ("controller.h", "MODES", ("firmware.rs", "MODES")),
    "Posture": ("controller.h", "POSTURES", ("firmware.rs", "POSTURES")),
    "Result": ("controller.h", "RESULTS", ("firmware.rs", "RESULTS")),
    "Fault": ("safety.h", "FAULTS", ("firmware.rs", "FAULTS")),
    "BusError": ("scs_bus.h", "BUS_ERRORS", None),
    "BenchMode": ("bench.h", "BENCH_MODES", ("firmware.rs", "BENCH_MODES")),
}


def round_half_away(x):
    """Round to nearest, halves away from zero: the firmware's round_to_long()."""
    return int(math.copysign(math.floor(abs(x) + 0.5), x))


def f(x):
    return f"{float(x)!r}f"


def b(x):
    return "true" if x else "false"


def arr(values):
    return "{" + ", ".join(f(v) for v in values) + "}"


def validate(r):
    names = [j["name"] for j in r["joints"]]
    if names != JOINT_ORDER:
        sys.exit(f"joints must be exactly, in order: {JOINT_ORDER}")
    if not 1 <= r["servo"]["reads_per_tick"] <= len(JOINT_ORDER):
        sys.exit(f"servo.reads_per_tick must be 1..{len(JOINT_ORDER)}")
    ids = [j["servo_id"] for j in r["joints"] if j["servo_id"] is not None]
    if len(ids) != len(set(ids)) or any(not (0 <= i <= 253) for i in ids):
        sys.exit("servo_id values must be unique and 0..253 (or null)")
    for j in r["joints"]:
        if j["direction"] not in (1, -1):
            sys.exit(f"{j['name']}: direction must be 1 or -1")
        if not j["min_deg"] <= j["max_deg"]:
            sys.exit(f"{j['name']}: min_deg > max_deg")
    for pose in ("STAND", "SIT"):
        for j in r["joints"][:NUM_POSE_JOINTS]:
            v = r["poses"][pose][j["name"]]
            if not j["min_deg"] <= v <= j["max_deg"]:
                sys.exit(f"pose {pose}: {j['name']} = {v} is outside its limits")
    g = r["hip_map"]["grid"]
    if [len(g[k]) for k in ("hip_pitch", "hip_roll", "hip_yaw", "knee")] != [13, 8, 3, 4]:
        sys.exit("hip map grid must be 13 x 8 x 3 x 4 (pitch, roll, yaw, knee); change robot_config.h too if it grows")
    if len(r["hip_map"]["rows"]) != 13 * 3 * 4:
        sys.exit("hip map: wrong number of rows")
    if len(r["motion"]["planned_trunk_pitch_deg"]) != 9:
        sys.exit("planned_trunk_pitch_deg must have 9 values")
    # The gyro's rates are turned into the body frame with this matrix, so it must be a rotation: anything else
    # would scale or mirror them (gravity is normalised afterwards and would not show the mistake).
    m = r["imu"]["sensor_to_body"]
    if len(m) != 3 or any(len(row) != 3 for row in m):
        sys.exit("imu.sensor_to_body must be 3 x 3")
    for i in range(3):
        for k in range(3):
            dot = sum(m[i][n] * m[k][n] for n in range(3))
            if abs(dot - (1.0 if i == k else 0.0)) > 1e-3:
                sys.exit("imu.sensor_to_body must be a rotation: its rows must be orthonormal")
    det = (m[0][0] * (m[1][1] * m[2][2] - m[1][2] * m[2][1]) - m[0][1] * (m[1][0] * m[2][2] - m[1][2] * m[2][0])
           + m[0][2] * (m[1][0] * m[2][1] - m[1][1] * m[2][0]))
    if det < 0:
        sys.exit("imu.sensor_to_body must be a rotation: its determinant is -1 (a mirror)")


def render(r):
    s = r["servo"]
    out = []
    w = out.append
    w("// SPDX-License-Identifier: Apache-2.0")
    w("// GENERATED by tools/gen_config.py from config/robot.json - do not edit by hand.")
    w("// Every number is provisional (design under review, nothing confirmed on a robot).")
    w("#pragma once")
    w('#include "robot_config.h"')
    w("")
    w("namespace duck {")
    w("")
    w("static const RobotConfig kRobotConfig = {")
    w(f"  /* servo */ {{{f(s['steps_per_deg'])}, {int(s['step_min'])}, {int(s['step_max'])}, {int(s['baud'])}u, "
      f"{int(s['goal_speed_steps_per_s'])}, {int(s['reads_per_tick'])}}},")
    w("  /* joints: servo id, zero step, direction, calibrated, min, max, max speed */ {")
    for j in r["joints"]:
        sid = "kServoIdUnassigned" if j["servo_id"] is None else str(int(j["servo_id"]))
        w(f'    {{{sid}, {int(j["zero_step"])}, {int(j["direction"])}, {b(j["calibrated"])}, '
          f'{f(j["min_deg"])}, {f(j["max_deg"])}, {f(j["max_speed_dps"])}}},  // {j["name"]}')
    w("  },")
    for pose in ("STAND", "SIT"):
        w(f"  /* {pose} */ {arr(r['poses'][pose][n] for n in POSE_JOINTS)},")
    h = r["head_interlock"]
    w(f"  /* head interlock */ {{{f(h['yaw_window_deg'])}, {f(h['yaw_margin_deg'])}, {f(h['roll_max_deg'])}, "
      f"{f(h['roll_margin_deg'])}, {f(h['roll_free_deg'])}}},")
    g = r["hip_map"]["grid"]
    rows = {(x["hip_pitch"], x["hip_yaw"], x["knee"]): x["roll_collides"] for x in r["hip_map"]["rows"]}
    w("  /* hip map */ {")
    w(f"    {arr(g['hip_pitch'])},")
    w(f"    {arr(g['hip_roll'])},")
    w(f"    {arr(g['hip_yaw'])},")
    w(f"    {arr(g['knee'])},")
    w("    {")
    for p in g["hip_pitch"]:
        cells = []
        for y in g["hip_yaw"]:
            vals = []
            for k in g["knee"]:
                bits = rows[(p, y, k)]
                if len(bits) != len(g["hip_roll"]) or set(bits) - {"0", "1"}:
                    sys.exit(f"hip map row {p}/{y}/{k}: bad roll_collides")
                vals.append("0x%02X" % sum(1 << i for i, c in enumerate(bits) if c == "1"))
            cells.append("{" + ", ".join(vals) + "}")
        w(f"      {{{', '.join(cells)}}},  // hip pitch {p:g}")
    w("    },")
    w("  },")
    m = r["motion"]
    w(f"  /* motion */ {{{f(m['sit_stand_seconds'])}, {f(m['return_to_stand_seconds'])}, {f(m['pose_tolerance_deg'])}, "
      f"{f(m['posture_detect_tolerance_deg'])},")
    w(f"    {arr(m['planned_trunk_pitch_deg'])}, {f(m['sit_uphill_limit_deg'])}, {b(m['head_motion_while_sitting'])}}},")
    bl = r["balance"]
    w(f"  /* balance */ {{{f(bl['ankle_gain'])}, {f(bl['lowpass_ms'])}, {f(bl['dead_zone_deg'])}, "
      f"{f(bl['max_correction_deg'])}}},")
    im = r["imu"]
    w("  /* imu */ {{" + ", ".join(arr(row) for row in im["sensor_to_body"]) + "}, "
      f"{b(im['calibrated'])}, {int(im['stale_ms'])}u, {b(im['require_to_arm'])}}},")
    fa = r["faults"]
    w(f"  /* faults */ {{{f(fa['overload_load_pct'])}, {f(fa['overload_seconds'])}, {f(fa['over_temp_c'])}, "
      f"{f(fa['under_voltage_v'])}, {int(fa['comm_fail_count'])}, {f(fa['fall_pitch_error_deg'])}, "
      f"{f(fa['fall_roll_deg'])}, {f(fa['fall_seconds'])}}},")
    w(f"  /* command timeout ms */ {int(r['command']['timeout_ms'])}u,")
    pr = r["servo_protection"]
    w(f"  /* servo protection */ {{{int(pr['unload_condition'])}, {int(pr['max_temperature_c'])}, "
      f"{int(pr['overload_torque_pct'])}, {int(pr['protection_time_10ms'])}, {int(pr['holding_torque_pct'])}}},")
    w("};")
    w("")
    w("}  // namespace duck")
    return "\n".join(out) + "\n"


def print_step_limits(r):
    spd = r["servo"]["steps_per_deg"]
    print("servo angle limits in steps (registers 9 / 11), from the joint table:")
    for j in r["joints"]:
        a = j["zero_step"] + j["direction"] * round_half_away(j["min_deg"] * spd)
        c = j["zero_step"] + j["direction"] * round_half_away(j["max_deg"] * spd)
        lo, hi = min(a, c), max(a, c)
        note = "" if j["calibrated"] else "   (PLACEHOLDER zero / direction)"
        warn = "   OUT OF 0..1023!" if lo < 0 or hi > 1023 else ""
        print(f"  {j['name']:16s} id {str(j['servo_id']):>4s}  {lo:5d} .. {hi:5d}{note}{warn}")


def enum_count(header, name):
    """How many values the C++ enum `name` in `header` has (enumerators are listed one by one, from 0)."""
    text = (CORE / header).read_text()
    m = re.search(r"enum\s+(?:class\s+)?" + name + r"\b[^{;]*\{(.*?)\};", text, re.S)
    if not m:
        sys.exit(f"{header}: enum {name} not found")
    body = re.sub(r"//[^\n]*", "", m.group(1))
    return len([e for e in body.split(",") if e.strip()])


def client_tables():
    tree = ast.parse(CLIENT.read_text())
    return {t.id: ast.literal_eval(node.value) for node in tree.body if isinstance(node, ast.Assign)
            for t in node.targets if isinstance(t, ast.Name) and isinstance(node.value, (ast.List, ast.Tuple))}


def rust_table_len(path, const):
    m = re.search(r"\bconst\s+" + const + r"\s*:\s*\[&(?:'static\s+)?str;\s*(\d+)\s*\]", path.read_text())
    if not m:
        sys.exit(f"{path.name}: no `const {const}: [&str; N]`")
    return int(m.group(1))


def check_name_tables():
    """Every name table outside the firmware has one entry per value of the firmware's enum."""
    problems = []
    for name, value in (("kNumJoints", len(JOINT_ORDER)), ("kNumPoseJoints", NUM_POSE_JOINTS)):
        m = re.search(r"constexpr int " + name + r" = (\d+);", (CORE / "robot_config.h").read_text())
        if not m or int(m.group(1)) != value:
            problems.append(f"robot_config.h: {name} is not {value}")
    client = client_tables()
    if client.get("JOINTS") != JOINT_ORDER:
        problems.append("duck_client.py: JOINTS is not the joint order of robot.json")
    for enum, (header, py_name, rust) in NAME_TABLES.items():
        n = enum_count(header, enum)
        if py_name not in client:
            problems.append(f"duck_client.py: no table {py_name} for {enum}")
        elif len(client[py_name]) != n:
            problems.append(f"duck_client.py: {py_name} has {len(client[py_name])} names, {enum} has {n} values")
        if rust is None:
            continue
        path = RUNTIME / rust[0]
        if not path.exists():
            print(f"(no {path.relative_to(HERE.parent.parent)}: the runtime's name tables were not checked)")
            continue
        size = rust_table_len(path, rust[1])
        if size != n:
            problems.append(f"runtime/src/{rust[0]}: {rust[1]} has {size} names, {enum} has {n} values")
    if problems:
        sys.exit("name tables out of step with the firmware:\n  " + "\n  ".join(problems))
    print(f"name tables agree with the firmware's enums ({', '.join(NAME_TABLES)})")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="only check that the header matches robot.json")
    a = ap.parse_args()
    r = json.loads(ROBOT_JSON.read_text())
    validate(r)
    text = render(r)
    if a.check:
        if not HEADER.exists() or HEADER.read_text() != text:
            sys.exit("robot_config_data.h is out of date: run tools/gen_config.py")
        print("robot_config_data.h is up to date")
        check_name_tables()
        return
    HEADER.write_text(text)
    print(f"wrote {HEADER.relative_to(HERE.parent)}")
    print_step_limits(r)


if __name__ == "__main__":
    main()
